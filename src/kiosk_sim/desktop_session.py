"""Persistent, day-by-day synthetic training for the desktop application."""
import copy
import csv
import json
import random
from dataclasses import asdict
from datetime import datetime
from pathlib import Path

from .ai.contextual import ContextualPolicy, FEATURES, OnlineContextualBandit
from .ai.fixed_bayesian import BayesianFixedOptimizer
from .generators import customers, stores
from .recommenders import FIXED_WEIGHTS
from .simulator import simulate


METRICS = ("score", "satisfaction", "store_satisfaction", "profit", "served",
           "avg_total_wait", "waste", "accept_rate")


def _normalise(values):
    total = sum(values)
    return tuple(value / total for value in values) if total else FIXED_WEIGHTS


def _mutate_fixed(weights, rng):
    return _normalise([max(.001, value + rng.gauss(0, .12)) for value in weights])


def _mutate_contextual(policy, rng):
    bias = list(policy.bias)
    coefficients = [list(row) for row in policy.coefficients]
    for _ in range(rng.randint(1, 3)):
        row = rng.randrange(4)
        if rng.random() < .25:
            bias[row] = max(-2., min(2., bias[row] + rng.gauss(0, .30)))
        else:
            column = rng.randrange(len(FEATURES))
            coefficients[row][column] = max(-2., min(2., coefficients[row][column] + rng.gauss(0, .45)))
    return ContextualPolicy(tuple(bias), tuple(tuple(row) for row in coefficients))


def _policy_data(policy):
    if isinstance(policy, OnlineContextualBandit):
        return policy.as_dict()
    return {"bias": list(policy.bias), "coefficients": [list(row) for row in policy.coefficients]}


def _policy_from_data(data):
    if data.get("policy_type") in ("online_contextual_bandit", "linucb_contextual_bandit"):
        return OnlineContextualBandit.from_dict(data)
    return ContextualPolicy(tuple(data["bias"]), tuple(tuple(row) for row in data["coefficients"]))


def _store_profile(store):
    """Stable, human-readable description of the generated synthetic shop."""
    menus = store.menus
    return {
        "purpose": store.purpose,
        "cooks": store.cooks,
        "initial_stock": dict(store.stock),
        "menu_count": len(menus),
        "average_price": sum(menu.price for menu in menus) / len(menus),
        "average_margin": sum(menu.price - menu.cost for menu in menus) / len(menus),
        "average_cook_minutes": sum(menu.cook_minutes for menu in menus) / len(menus),
        "average_expiry_risk": sum(menu.expiry_risk for menu in menus) / len(menus),
        "menus": [{"name": menu.name, "price": menu.price, "margin": menu.price - menu.cost,
                   "cook_minutes": menu.cook_minutes, "expiry_risk": menu.expiry_risk}
                  for menu in menus],
    }


class TrainingSession:
    """Online comparison using one identical synthetic day per model and step."""

    def __init__(self, *, visitors, seed=42, test_days=12, menus=8, title="새 실행"):
        if visitors < 1 or test_days < 1 or menus < 2:
            raise ValueError("방문자 수와 평가일은 1 이상, 메뉴 수는 2 이상이어야 합니다.")
        self.data = {
            "format": 1,
            "title": title,
            "created_at": datetime.now().isoformat(timespec="seconds"),
            "config": {"visitors_per_day": visitors, "seed": seed, "test_days": test_days, "menus": menus},
            "status": "training",
            "training_days": [],
            "evaluation_days": [],
            "evaluation_counts": {"optimized_fixed": 0, "contextual": 0, "baseline_fixed": 0, "no_recommendation": 0},
            "fixed_policy": list(FIXED_WEIGHTS),
            "fixed_optimizer": BayesianFixedOptimizer(seed=seed + 20_000).as_dict(),
            "contextual_policy": _policy_data(OnlineContextualBandit(seed=seed + 30_000)),
            "learning_method": "incremental online contextual bandit",
            "best_training_score": {"optimized_fixed": None, "contextual": None},
            "frozen_models": None,
            "note": "All outcomes are generated by a synthetic simulation. They do not establish real customer effects.",
        }
        self._shop = stores(1, random.Random(seed), menus)[0]
        self.data["store_profile"] = _store_profile(self._shop)

    @classmethod
    def load(cls, path):
        with open(path, encoding="utf-8") as handle:
            data = json.load(handle)
        session = cls.__new__(cls)
        session.data = data
        # Records written by the first desktop release remain resumable.
        session.data.setdefault("best_training_score", {"optimized_fixed": None, "contextual": None})
        session.data.setdefault("evaluation_counts", {"optimized_fixed": 0, "contextual": 0})
        session.data["evaluation_counts"].setdefault("baseline_fixed", 0)
        session.data["evaluation_counts"].setdefault("no_recommendation", 0)
        session.data.setdefault("fixed_optimizer", BayesianFixedOptimizer(seed=data["config"]["seed"] + 20_000).as_dict())
        config = data["config"]
        session._shop = stores(1, random.Random(config["seed"]), config["menus"])[0]
        session.data.setdefault("store_profile", _store_profile(session._shop))
        session._ensure_reference_rows()
        return session

    @property
    def path_title(self):
        return self.data.get("title", "실행 기록")

    def _day(self, index, testing=False):
        config = self.data["config"]
        offset = 1_000_003 if testing else 10_003
        rng = random.Random(config["seed"] + offset + index * 997)
        shop = copy.deepcopy(self._shop)
        shop.stock = {ingredient: rng.randint(28, 60) for ingredient in self._shop.stock}
        shop.cook_free_at = [0.] * shop.cooks
        return customers(config["visitors_per_day"], rng, shop), shop, rng.randrange(2 ** 32)

    def train_one_day(self):
        if self.data["status"] != "training":
            raise RuntimeError("학습이 진행 중인 실행 기록이 아닙니다.")
        index = len(self.data["training_days"]) + 1
        config = self.data["config"]
        people, shop, event_seed = self._day(index)
        fixed_optimizer = BayesianFixedOptimizer.from_dict(self.data["fixed_optimizer"])
        fixed = fixed_optimizer.propose()
        fixed_result = simulate(people, shop, "fixed", fixed, event_seed)
        fixed_optimizer.observe(fixed, fixed_result.score)
        self.data["fixed_optimizer"] = fixed_optimizer.as_dict()
        self.data["fixed_policy"] = list(fixed_optimizer.best_weights)
        self.data["best_training_score"]["optimized_fixed"] = fixed_result.score
        contextual = _policy_from_data(self.data["contextual_policy"])
        feedback = []
        contextual_result = simulate(people, shop, "gemini", contextual, event_seed, feedback=feedback)
        for observation in feedback:
            if "bandit_features" in observation:
                reward = .65 * observation["customer_satisfaction"] + .35 * observation["store_satisfaction"]
                contextual.observe(observation["bandit_features"], reward)
        self.data["contextual_policy"] = _policy_data(contextual)
        self.data["best_training_score"]["contextual"] = contextual_result.score
        baseline_result = simulate(people, shop, "fixed", FIXED_WEIGHTS, event_seed)
        none_result = simulate(people, shop, "none", FIXED_WEIGHTS, event_seed)
        self.data["evaluation_counts"]["optimized_fixed"] += 1
        self.data["evaluation_counts"]["contextual"] += 1
        self.data["evaluation_counts"]["baseline_fixed"] += 1
        self.data["evaluation_counts"]["no_recommendation"] += 1
        row = {"day": index, "event_seed": event_seed, "optimized_fixed": asdict(fixed_result),
               "contextual": asdict(contextual_result), "baseline_fixed": asdict(baseline_result),
               "no_recommendation": asdict(none_result),
               "fixed_weights": list(self.data["fixed_policy"]),
               "contextual_reference_weights": list(contextual.base_weights),
               "fixed_candidate_retained": self.data["fixed_policy"] == list(fixed),
               "fixed_optimizer_trial": fixed_optimizer.trial,
               "contextual_updates": len(feedback),
               "contextual_total_updates": contextual.updates,
               "contextual_reward_mean": contextual.reward_mean}
        self.data["training_days"].append(row)
        return row

    def freeze_and_evaluate(self):
        if self.data["status"] == "evaluated":
            return self.data["evaluation_days"]
        self.data["status"] = "evaluating"
        fixed = tuple(self.data["fixed_policy"])
        contextual = _policy_from_data(self.data["contextual_policy"])
        if hasattr(contextual, "frozen"):
            contextual = contextual.frozen()
        self.data["frozen_models"] = {"optimized_fixed": list(fixed), "contextual": _policy_data(contextual)}
        rows = []
        for index in range(1, self.data["config"]["test_days"] + 1):
            people, shop, event_seed = self._day(index, testing=True)
            fixed_result = simulate(people, shop, "fixed", fixed, event_seed)
            contextual_result = simulate(people, shop, "gemini", contextual, event_seed)
            baseline_result = simulate(people, shop, "fixed", FIXED_WEIGHTS, event_seed)
            none_result = simulate(people, shop, "none", FIXED_WEIGHTS, event_seed)
            self.data["evaluation_counts"]["optimized_fixed"] += 1
            self.data["evaluation_counts"]["contextual"] += 1
            self.data["evaluation_counts"]["baseline_fixed"] += 1
            self.data["evaluation_counts"]["no_recommendation"] += 1
            rows.append({"day": index, "event_seed": event_seed,
                         "optimized_fixed": asdict(fixed_result), "contextual": asdict(contextual_result),
                         "baseline_fixed": asdict(baseline_result), "no_recommendation": asdict(none_result)})
        self.data["evaluation_days"] = rows
        self.data["status"] = "evaluated"
        return rows

    def _ensure_reference_rows(self):
        """Backfill non-learning comparison policies for old saved records."""
        baseline_expected = none_expected = 0
        for testing, rows in ((False, self.data["training_days"]), (True, self.data["evaluation_days"])):
            for index, row in enumerate(rows, 1):
                if "baseline_fixed" in row:
                    baseline_expected += 1
                else:
                    people, shop, event_seed = self._day(index, testing=testing)
                    row["baseline_fixed"] = asdict(simulate(people, shop, "fixed", FIXED_WEIGHTS, event_seed))
                    baseline_expected += 1
                if "no_recommendation" in row:
                    none_expected += 1
                else:
                    people, shop, event_seed = self._day(index, testing=testing)
                    row["no_recommendation"] = asdict(simulate(people, shop, "none", FIXED_WEIGHTS, event_seed))
                    none_expected += 1
        self.data["evaluation_counts"]["baseline_fixed"] = baseline_expected
        self.data["evaluation_counts"]["no_recommendation"] = none_expected

    def final_differences(self):
        rows = self.data["evaluation_days"] or self.data["training_days"]
        if not rows:
            return {}
        return {metric: sum(row["contextual"][metric] - row["optimized_fixed"][metric] for row in rows) / len(rows)
                for metric in METRICS}

    def superiority(self):
        """Each policy's score advantage against the no-recommendation reference."""
        rows = self.data["evaluation_days"] or self.data["training_days"]
        if not rows:
            return {}
        reference = sum(row["no_recommendation"]["score"] for row in rows) / len(rows)
        result = {}
        for model in ("baseline_fixed", "optimized_fixed", "contextual"):
            average = sum(row[model]["score"] for row in rows) / len(rows)
            wins = sum(row[model]["score"] > row["no_recommendation"]["score"] + 1e-12 for row in rows)
            result[model] = {"average_score": average,
                             "relative_percent": 100 * (average - reference) / max(abs(reference), 1e-12),
                             "better_days": wins, "days": len(rows)}
        return result

    def save(self, path):
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as handle:
            json.dump(self.data, handle, ensure_ascii=False, indent=2)
        self._write_csv(path.with_name("daily_results.csv"))

    def _write_csv(self, path):
        rows = []
        for phase, daily in (("training", self.data["training_days"]), ("held_out_evaluation", self.data["evaluation_days"])):
            for row in daily:
                for model in ("no_recommendation", "baseline_fixed", "optimized_fixed", "contextual"):
                    rows.append({"phase": phase, "day": row["day"], "model": model, **row[model]})
        if not rows:
            return
        with open(path, "w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=rows[0].keys())
            writer.writeheader()
            writer.writerows(rows)
